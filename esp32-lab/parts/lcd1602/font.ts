const SPECIAL: Record<number, string> = { 0xdf: '0705070000', 0xff: '7f7f7f7f7f' };

/** Column bytes of character `code` in the ROM (blank if it has none). */
export function glyph(code: number): number[] {
  const hex = code >= 0x20 && code < 0x80 ? ASCII[code - 0x20] : SPECIAL[code];
  if (!hex) return [0, 0, 0, 0, 0];
  return [0, 2, 4, 6, 8].map((i) => parseInt(hex.slice(i, i + 2), 16));
}
