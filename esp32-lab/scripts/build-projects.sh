#!/usr/bin/env bash
# Build every featured project's main.cpp with PlatformIO, for test/projects.test.ts.
# Each gets its own PlatformIO project in .build/projects/<id> whose [env] copies the lesson
# project's shared [env] (same platform, board and core as `pio run -e lessonNN`).
set -euo pipefail
cd "$(dirname "$0")/.."
PIO="${PIO:-$HOME/.platformio/penv/bin/pio}"
[ -x "$PIO" ] || PIO=pio
shared=$(awk '/^\[env\]$/{on=1; next} /^\[/{on=0} on' ../platformio.ini)
for dir in projects/*/; do
  id=$(basename "$dir")
  out=".build/projects/$id"
  mkdir -p "$out/src"
  # Libraries for the headers the sketch includes, as the lab's own build adds them
  libs=$(node -e '
    const map = require("./packages/lab-server/libraries.json");
    const code = require("fs").readFileSync(process.argv[1], "utf8");
    const deps = new Set();
    for (const m of code.matchAll(/^\s*#\s*include\s*[<"]([^>"]+)[>"]/gm)) if (map[m[1]]) deps.add(map[m[1]]);
    if (deps.size) console.log(["lib_deps =", ...[...deps].map((d) => "  " + d)].join("\n"));
  ' "$dir/main.cpp")
  printf '; Generated by scripts/build-projects.sh\n[env:%s]\n%s\n%s\n' "$id" "$shared" "$libs" > "$out/platformio.ini"
  cp "$dir/main.cpp" "$out/src/main.cpp"
  echo "== $id"
  "$PIO" run -d "$out" -s
done
