// Dev-server endpoints that compile the sketch typed in the browser with the real PlatformIO
// toolchain, then serve the build outputs to the emulator.
//
//   POST /api/build            { code }  → streams the `pio run` log as text, then a final
//                                          line "@@RESULT {json}" with ok / duration / errors
//   GET  /api/build/out/<file>           firmware.elf | firmware.bin | bootloader.bin | partitions.bin
//   GET  /api/sketch?path=lession/...    a lesson's main.cpp, as starting code
//
// The sketch lives in its own PlatformIO project (esp32-lab/.build/sketch) whose [env] copies
// platform / board / framework from the lesson project's platformio.ini, so it builds against
// exactly the same core as `pio run -e lessonNN`. The user's platformio.ini is never touched.

import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, normalize, relative } from 'node:path';
import type { Plugin } from 'vite';

export interface BuildError {
  line: number;
  column: number;
  severity: 'error' | 'warning';
  message: string;
}

const FILES = ['firmware.elf', 'firmware.bin', 'bootloader.bin', 'partitions.bin'];
const ENV = 'sketch';

function pioCommand(): string {
  if (process.env.PIO) return process.env.PIO;
  const penv = join(homedir(), '.platformio/penv/bin/pio');
  return existsSync(penv) ? penv : 'pio';
}

/** platform / board / framework / build options from the lesson project's shared [env]. */
function sharedEnv(projectIni: string): string[] {
  if (!existsSync(projectIni)) return ['platform = espressif32', 'board = esp32dev', 'framework = arduino'];
  const keep = ['platform', 'platform_packages', 'board', 'framework', 'board_build.', 'build_flags', 'lib_deps'];
  const lines: string[] = [];
  let inEnv = false;
  for (const raw of readFileSync(projectIni, 'utf8').split('\n')) {
    const line = raw.replace(/\s;.*$/, '').trimEnd();
    if (/^\[.*\]$/.test(line.trim())) inEnv = line.trim() === '[env]';
    else if (inEnv && keep.some((k) => line.trim().startsWith(k))) lines.push(line.trim());
  }
  return lines;
}

/** GCC diagnostics for src/main.cpp. */
export function parseErrors(log: string): BuildError[] {
  const out: BuildError[] = [];
  const re = /(?:^|[\s/\\])src[/\\]main\.cpp:(\d+):(\d+): (fatal error|error|warning): (.*)$/gm;
  for (let m = re.exec(log); m; m = re.exec(log)) {
    out.push({ line: Number(m[1]), column: Number(m[2]), severity: m[3] === 'warning' ? 'warning' : 'error', message: m[4]! });
  }
  return out;
}

export function sketchBuilds(opts: { workDir: string; projectRoot: string }): Plugin {
  const project = join(opts.workDir, 'sketch');
  const outDir = join(project, '.pio', 'build', ENV);
  let building = false;

  function prepare(code: string) {
    mkdirSync(join(project, 'src'), { recursive: true });
    const ini = [
      '; Generated by ESP32 Lab for the code editor – edits are overwritten',
      `[env:${ENV}]`,
      ...sharedEnv(join(opts.projectRoot, 'platformio.ini')),
      '',
    ].join('\n');
    const iniPath = join(project, 'platformio.ini');
    if (!existsSync(iniPath) || readFileSync(iniPath, 'utf8') !== ini) writeFileSync(iniPath, ini);
    writeFileSync(join(project, 'src', 'main.cpp'), code);
  }

  return {
    name: 'esp32lab-sketch-builds',
    configureServer(server) {
      server.middlewares.use('/api/build', (req, res, next) => {
        const path = (req.url ?? '/').split('?')[0]!;
        if (req.method === 'GET' && path.startsWith('/out/')) {
          const file = path.slice(5);
          const full = join(outDir, file);
          if (!FILES.includes(file) || !existsSync(full)) return next();
          res.setHeader('content-type', 'application/octet-stream');
          res.setHeader('cache-control', 'no-store');
          return res.end(readFileSync(full));
        }
        if (req.method !== 'POST' || path !== '/') return next();
        if (building) {
          res.statusCode = 409;
          return res.end('Đang build, chờ lần build trước xong.');
        }
        let body = '';
        req.on('data', (c) => (body += c));
        req.on('end', () => {
          let code: string;
          try {
            code = String(JSON.parse(body).code ?? '');
          } catch {
            res.statusCode = 400;
            return res.end('bad request');
          }
          building = true;
          prepare(code);
          res.setHeader('content-type', 'text/plain; charset=utf-8');
          res.setHeader('cache-control', 'no-store');
          const started = Date.now();
          let log = '';
          const child = spawn(pioCommand(), ['run', '-d', project, '-e', ENV], { env: { ...process.env, PLATFORMIO_FORCE_ANSI: 'false' } });
          const pipe = (d: Buffer) => {
            const text = d.toString();
            log += text;
            res.write(text);
          };
          child.stdout.on('data', pipe);
          child.stderr.on('data', pipe);
          child.on('error', (e) => pipe(Buffer.from(`\nKhông chạy được PlatformIO (${pioCommand()}): ${e.message}\nCài PlatformIO hoặc đặt biến môi trường PIO.\n`)));
          child.on('close', (status) => {
            building = false;
            const ok = status === 0 && FILES.slice(0, 2).every((f) => existsSync(join(outDir, f)));
            res.end(`\n@@RESULT ${JSON.stringify({ ok, ms: Date.now() - started, errors: parseErrors(log) })}\n`);
          });
        });
      });

      server.middlewares.use('/api/sketch', (req, res, next) => {
        const rel = new URL(req.url ?? '/', 'http://x').searchParams.get('path') ?? '';
        const full = normalize(join(opts.projectRoot, rel));
        // Only lesson sources from the course folder
        if (!rel.endsWith('.cpp') || relative(join(opts.projectRoot, 'lession'), full).startsWith('..') || !existsSync(full)) return next();
        res.setHeader('content-type', 'text/plain; charset=utf-8');
        res.end(readFileSync(full, 'utf8'));
      });
    },
  };
}
